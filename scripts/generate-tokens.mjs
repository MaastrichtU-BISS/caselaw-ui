/** The canonical token definitions generate both CSS and the typed JavaScript API. */
import { readFileSync, writeFileSync } from 'node:fs';
const { tokens, theme, themes = {} } = JSON.parse(
  readFileSync(new URL('../src/theme/tokens.json', import.meta.url), 'utf8'),
);
function resolve(value) {
  if (typeof value === 'string') return tokens[value] ?? value;
  return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v)]));
}
const block = (selector, values, scheme) =>
  selector +
  ' {\n' +
  (scheme ? '  color-scheme: ' + scheme + ';\n' : '') +
  Object.entries(values)
    .map(([k, v]) => '  ' + k + ': ' + v + ';')
    .join('\n') +
  '\n}\n';
const lightOverrides = Object.fromEntries(
  Object.keys(themes.dark ?? {}).map((name) => [name, tokens[name]]),
);
/*
 * Themes are scoped: set data-biss-theme on <html> or on any wrapper.
 * "dark" and "light" force a palette (and can be nested inside each other);
 * "system" follows the operating system preference.
 */
const css =
  '/* Generated by scripts/generate-tokens.mjs from src/theme/tokens.json. */\n' +
  block(':root', tokens) +
  (themes.dark
    ? block("[data-biss-theme='light']", lightOverrides, 'light') +
      block("[data-biss-theme='dark']", themes.dark, 'dark') +
      '@media (prefers-color-scheme: dark) {\n' +
      block("  [data-biss-theme='system']", themes.dark, 'dark')
        .split('\n')
        .map((line) => (line && !line.startsWith('  [') ? '  ' + line : line))
        .join('\n') +
      '}\n'
    : '');
const js =
  '/** Generated from src/theme/tokens.json; edit that source rather than these values. */\nexport const bissCssTokens = ' +
  JSON.stringify(tokens, null, 2) +
  ' as const;\nexport const bissThemes = ' +
  JSON.stringify(themes, null, 2) +
  ' as const;\nexport type BissThemeName = "light" | keyof typeof bissThemes | "system";\nexport const bissTheme = ' +
  JSON.stringify(resolve(theme), null, 2) +
  ' as const;\nexport type BissTheme = typeof bissTheme;\nexport type BissTokenName = keyof typeof bissCssTokens;\nexport type {BissLink} from "./core/types";\n';
for (const [path, contents] of [
  ['src/styles/tokens.css', css],
  ['src/tokens.ts', js],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== contents)
      throw Error(path + ' is out of sync. Run npm run tokens:generate.');
  } else writeFileSync(path, contents);
}
